package com.onpath.app.map

import android.content.Context
import android.util.Log
import com.onpath.app.data.DataFiles
import com.onpath.app.debug.Problems
import org.json.JSONObject
import java.io.File

/**
 * Builds the style JSON for a map theme (e.g. "classic", "high-contrast"), with {DATA_DIR} replaced.
 *
 * Styling is meant to change often, so the app looks for the theme file in this order:
 * 1. `<dataDir>/styles/onpath[-theme].json` – an override pushed with adb (or later downloaded),
 *    so the look can be updated without a new APK;
 * 2. the bundled asset `style/onpath[-theme].json`;
 * 3. the bundled classic style; 4. a minimal inline style.
 * Files are generated by `tools/make_style.py --theme <name>` from `tools/themes/<name>.json`.
 *
 * Two map package formats exist (docs/map-pipeline.md): format 1 (overlays as GeoJSON files, style `style/onpath.json`)
 * and format 2 (one `overlays.pmtiles`, style `style/f2/onpath.json`). The data folder decides
 * ([DataFiles.formatOf]); an override written for the other format is skipped (metadata `onpath:format`).
 */
object StyleLoader {

    const val STYLE_ASSET = "style/onpath.json"
    const val DEFAULT_THEME = "classic"
    private const val ASSET_DIR = "style"
    const val OVERRIDE_DIR = "styles"

    /** Which style the last [load] used ("override onpath.json", "asset onpath.json", "fallback") – diagnostics. */
    @Volatile var lastLoaded: String? = null
        private set

    /** MapLibre rejected the style ([msg]) and the app switched to the fallback – kept for diagnostics. */
    fun noteFailure(msg: String) {
        Problems.error("map", "Map style failed to load: $msg – fallback style used, map mostly empty")
        lastLoaded = "FAILED (${lastLoaded ?: "?"}): $msg → fallback"
    }

    /** Asset folder of the styles for map package [format] ("style", "style/f2"). */
    fun assetDir(format: Int): String = if (format >= 2) "$ASSET_DIR/f$format" else ASSET_DIR

    /** Map package format a style file is written for (metadata "onpath:format", missing = 1). Never throws. */
    fun styleFormat(json: String): Int = try {
        JSONObject(json).optJSONObject("metadata")?.optInt("onpath:format", 1) ?: 1
    } catch (e: Exception) {
        // expected: not JSON at all – load() rejects such a file anyway
        1
    }

    /** File name of a theme: classic is "onpath.json", others "onpath-<theme>.json". */
    fun fileName(theme: String): String =
        if (theme == DEFAULT_THEME || theme.isBlank()) "onpath.json" else "onpath-$theme.json"

    /** Theme name from a file name, or null if it is not a style file. */
    fun themeOf(fileName: String): String? = when {
        fileName == "onpath.json" -> DEFAULT_THEME
        fileName.startsWith("onpath-") && fileName.endsWith(".json") ->
            fileName.removePrefix("onpath-").removeSuffix(".json").takeIf { it.isNotBlank() }
        else -> null
    }

    /** All themes available (bundled + overrides), classic first. */
    fun themes(context: Context, dataDir: File): List<String> {
        val names = linkedSetOf(DEFAULT_THEME)
        try { context.assets.list(ASSET_DIR)?.forEach { f -> themeOf(f)?.let { names += it } } }
        catch (e: Exception) { Problems.warn("map", "Bundled map themes not listable, only classic offered", e) }
        File(dataDir, OVERRIDE_DIR).listFiles()?.forEach { f -> themeOf(f.name)?.let { names += it } }
        return names.toList()
    }

    /** Human label for a theme key ("high-contrast" → "High contrast"). */
    fun label(theme: String): String =
        theme.replace('-', ' ').replace('_', ' ').replaceFirstChar { it.uppercase() }

    /** Folder the last [load] took the map files from (the data folder or a cell store generation). */
    @Volatile var lastMapDir: File? = null
        private set

    /**
     * Style JSON for [theme]. Style overrides come from [dataDir]/styles; the map files ({DATA_DIR}) from [mapDir] –
     * the data folder, or the current generation of downloaded map cells (DataFiles.mapDir, map-cells.md §19).
     */
    fun load(context: Context, dataDir: File, theme: String = DEFAULT_THEME, mapDir: File = dataDir): String {
        // a theme that no longer exists (e.g. "high-contrast", removed in 0.7.0) is simply the default – no error
        @Suppress("NAME_SHADOWING")
        val theme = if (theme == DEFAULT_THEME || theme in themes(context, dataDir)) theme else DEFAULT_THEME
        val dir = mapDir.absolutePath
        lastMapDir = mapDir
        val format = DataFiles.formatOf { File(mapDir, it).isFile }
        val assets = assetDir(format)
        val tag = if (format == 1) "" else " (format $format)"
        val attempts = buildList<Pair<String, () -> String>> {
            val override = File(File(dataDir, OVERRIDE_DIR), fileName(theme))
            // expected: usually there is no override file – only a present but broken / other-format one is reported
            if (override.exists()) add("override ${override.name}" to {
                val json = override.readText()
                val f = styleFormat(json)
                if (f != format) throw IllegalStateException("written for map format $f, the map data is format $format")
                json
            })
            add("asset ${fileName(theme)}$tag" to { context.assets.open("$assets/${fileName(theme)}").bufferedReader().use { it.readText() } })
            if (theme != DEFAULT_THEME) add("asset classic$tag" to { context.assets.open("$assets/onpath.json").bufferedReader().use { it.readText() } })
        }
        for ((what, read) in attempts) {
            try {
                val json = read()
                if (!json.trimStart().startsWith("{")) error("not JSON")
                Log.i("OnPath", "Map style: $what")
                lastLoaded = what
                return OptionalSources.strip(Overview.merge(json.replace("{DATA_DIR}", dir), Overview.bundled(context)))
            } catch (e: Exception) {
                Problems.warn("map", "Map style $what not usable, trying the next one", e)
            }
        }
        Problems.error("map", "No map style file usable – minimal fallback style used, map mostly empty")
        lastLoaded = "fallback"
        return fallback(mapDir)
    }

    /** Small but usable style: base map basics + route overlays, if the data files exist. */
    fun fallback(dataDir: File): String {
        val dir = dataDir.absolutePath
        val hasBase = File(dataDir, "base.pmtiles").isFile
        val hasRoutes = File(dataDir, "routes.geojson").isFile
        val hasOverlays = File(dataDir, DataFiles.OVERLAYS).isFile
        val sources = mutableListOf<String>()
        val layers = mutableListOf("""{"id":"background","type":"background","paint":{"background-color":"#f3f1e8"}}""")
        if (hasBase) {
            sources += """"base":{"type":"vector","url":"pmtiles://file://$dir/base.pmtiles","attribution":"© OpenStreetMap contributors"}"""
            layers += """{"id":"wood","type":"fill","source":"base","source-layer":"landcover","filter":["==",["get","class"],"wood"],"paint":{"fill-color":"#d6e8c4"}}"""
            layers += """{"id":"grass","type":"fill","source":"base","source-layer":"landcover","filter":["==",["get","class"],"grass"],"paint":{"fill-color":"#e6efd6"}}"""
            layers += """{"id":"water","type":"fill","source":"base","source-layer":"water","paint":{"fill-color":"#a9d3ef"}}"""
            layers += """{"id":"waterway","type":"line","source":"base","source-layer":"waterway","paint":{"line-color":"#a9d3ef","line-width":1.2}}"""
            layers += """{"id":"roads","type":"line","source":"base","source-layer":"transportation","filter":["!",["in",["get","class"],["literal",["path","track"]]]],"paint":{"line-color":"#ffffff","line-width":["interpolate",["linear"],["zoom"],10,1,16,6]}}"""
            layers += """{"id":"tracks","type":"line","source":"base","source-layer":"transportation","filter":["==",["get","class"],"track"],"paint":{"line-color":"#8a6d3b","line-width":1.5,"line-dasharray":[3,1]}}"""
            layers += """{"id":"paths","type":"line","source":"base","source-layer":"transportation","filter":["==",["get","class"],"path"],"paint":{"line-color":"#7a3b2e","line-width":1.4,"line-dasharray":[2,1.5]}}"""
            layers += """{"id":"buildings","type":"fill","source":"base","source-layer":"building","minzoom":14,"paint":{"fill-color":"#ddd6cc"}}"""
        }
        if (hasOverlays) {
            // format 2: the base map has no path / track lines at z13+ – draw the overlay's paths
            sources += """"overlays":{"type":"vector","url":"pmtiles://file://$dir/${DataFiles.OVERLAYS}"}"""
            layers += """{"id":"own-paths","type":"line","source":"overlays","source-layer":"paths","minzoom":13,"filter":["in",["get","k"],["literal",["p","t"]]],"paint":{"line-color":"#7a3b2e","line-width":1.4}}"""
            for (kind in listOf("hike", "bike", "mtb")) {
                layers += """{"id":"routes-$kind","type":"line","source":"overlays","source-layer":"routes","filter":["==",["get","kind"],"$kind"],"layout":{"visibility":"none","line-join":"round"},"paint":{"line-color":"#3fa34d","line-opacity":0.35,"line-width":8}}"""
            }
        } else if (hasRoutes) {
            sources +=""""routes":{"type":"geojson","data":"file://$dir/routes.geojson"}"""
            for (kind in listOf("hike", "bike", "mtb")) {
                layers += """{"id":"routes-$kind","type":"line","source":"routes","filter":["==",["get","kind"],"$kind"],"layout":{"visibility":"none","line-join":"round"},"paint":{"line-color":"#3fa34d","line-opacity":0.35,"line-width":8}}"""
            }
        }
        return """{"version":8,"name":"OnPath fallback","sources":{${sources.joinToString(",")}},"layers":[${layers.joinToString(",")}]}"""
    }
}
