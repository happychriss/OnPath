#!/usr/bin/env bash
# Sets up (or updates) the OnPath map server on a fresh Ubuntu 24.04 machine. Run as root; safe to run again.
# Called by cloud-init on the new Hetzner server (see tools/hetzner/onpath_hetzner.py), or by hand:
#   bash /opt/onpath/repo/tools/hetzner/server/install.sh [--domain maps.example.org]
#
# Installs: Java 21, osmium-tool, Python venv with the pipeline packages, Caddy (HTTPS, password),
# systemd services onpath-api / onpath-worker and the monthly onpath-refresh timer. Data under /srv/onpath.
# It touches nothing outside these paths and the packages it installs: meant for its own, new server.
set -euo pipefail

DOMAIN=""
while [ $# -gt 0 ]; do case "$1" in --domain) DOMAIN=${2:-}; shift ;; esac; shift; done

REPO=/opt/onpath/repo
SRV=$REPO/tools/hetzner/server
VENV=/opt/onpath/venv
HOME_DIR=/srv/onpath
ETC=/etc/onpath
log() { printf '[%s] %s\n' "$(date +%H:%M:%S)" "$*"; }

[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
[ -d "$REPO/.git" ] || { echo "repo missing at $REPO (git clone https://github.com/happychriss/OnPath $REPO)" >&2; exit 1; }

log "packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q openjdk-21-jre-headless osmium-tool python3-venv python3-pip curl unzip git caddy \
  ca-certificates unattended-upgrades >/dev/null

log "swap (Planetiler peaks above RAM on big regions)"
if ! swapon --show | grep -q .; then
  fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap -q /swapfile && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

log "user and folders"
id onpath >/dev/null 2>&1 || useradd --system --home-dir "$HOME_DIR" --shell /usr/sbin/nologin onpath
mkdir -p "$HOME_DIR"/{state,work,build,logs,public/dl} "$ETC"
chown -R onpath:onpath "$HOME_DIR"
chmod 755 "$HOME_DIR" "$HOME_DIR/public" "$HOME_DIR/public/dl"
# the worker pulls the repo before each build (pipeline + styles stay current)
chown -R onpath:onpath /opt/onpath/repo
git config --system --add safe.directory "$REPO" 2>/dev/null || true

log "python venv"
[ -x "$VENV/bin/python" ] || python3 -m venv "$VENV"
"$VENV/bin/pip" install -q --upgrade pip
"$VENV/bin/pip" install -q osmium shapely pmtiles numpy pillow contourpy mapbox-vector-tile

log "host name and password"
if [ -n "$DOMAIN" ]; then echo "$DOMAIN" > "$ETC/host"; fi
if [ ! -s "$ETC/host" ]; then
  IP=$(curl -fsS --max-time 5 http://169.254.169.254/hetzner/v1/metadata/public-ipv4 || hostname -I | awk '{print $1}')
  echo "${IP//./-}.sslip.io" > "$ETC/host"   # free host name pointing at the IP, so Caddy gets a real certificate
fi
HOST=$(cat "$ETC/host")
if [ ! -s "$ETC/password.txt" ]; then
  umask 077; head -c 18 /dev/urandom | base64 | tr -d '/+=' | head -c 20 > "$ETC/password.txt"; umask 022
fi
HASH=$(caddy hash-password --plaintext "$(cat "$ETC/password.txt")")
chmod 600 "$ETC/password.txt"

log "caddy ($HOST)"
cat > /etc/caddy/Caddyfile <<EOF
# OnPath map server – generated by $SRV/install.sh, do not edit (run install.sh again instead)
$HOST {
	encode gzip
	# downloads are public: the folder names carry a random token, so links work in any browser / the app
	handle /dl/* {
		root * $HOME_DIR/public
		file_server
	}
	handle {
		basicauth {
			onpath $HASH
		}
		handle /api/* {
			reverse_proxy 127.0.0.1:8090
		}
		handle {
			root * $SRV/web
			file_server
		}
	}
}
EOF
systemctl enable -q caddy
systemctl reload caddy 2>/dev/null || systemctl restart caddy

log "systemd services"
for u in onpath-api.service onpath-worker.service onpath-refresh.service onpath-refresh.timer; do
  sed -e "s#@SRV@#$SRV#g" -e "s#@VENV@#$VENV#g" -e "s#@HOME@#$HOME_DIR#g" -e "s#@REPO@#$REPO#g" \
    "$SRV/systemd/$u" > "/etc/systemd/system/$u"
done
systemctl daemon-reload
systemctl enable -q --now onpath-api.service onpath-worker.service onpath-refresh.timer
systemctl restart onpath-api.service onpath-worker.service

date -u +%FT%TZ > "$ETC/ready"
log "done: https://$HOST  (user onpath, password in $ETC/password.txt)"
