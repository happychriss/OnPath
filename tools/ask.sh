#!/usr/bin/env bash
# Questions to the owner and the owner's word to every session – as GitHub issues in the private repo
# happychriss/onpath.private (owner 2026-11-01, docs/roles/setup-vorschlag-2026-11-01.md §4b). One place, on the phone.
#
#   label `frage`   – a session asks the owner. One question per issue, always the same shape (who, 2–3 lines of
#                     background, the question, options with the recommendation first, a link). The owner answers
#                     with a comment ("A"); the session acts and closes the issue with one line.
#   label `an-alle` – the owner's (or the captain's) word to every session: a rule, a priority change, a stop. Every
#                     session reads the open ones at the start, after every pull and before every push (gate.sh) and
#                     confirms once with "gelesen – <unit>". `#push-sperre` in the text: gate.sh refuses every push;
#                     `#release-sperre`: gate.sh refuses a release commit (version line / release notes).
#
# Usage:
#   tools/ask.sh frage --von donald --titel "Debug-Build für Tester?" --worum "2–3 Zeilen" \
#                      --frage "…?" --a "… (Empfehlung)" --b "…" [--c "…"] [--details docs/x.md#y]
#   tools/ask.sh offen [--von donald]      open questions + their last comment (= the owner's answer, if any)
#   tools/ask.sh erledigt <nr> "was gemacht wurde"     comment + close a question
#   tools/ask.sh an-alle [--von donald]    print the open `an-alle` issues (and confirm them as read with --von)
#   tools/ask.sh sag --titel "…" --text "…"            new `an-alle` issue (owner / captain)
#   tools/ask.sh check [--release]         for gate.sh: print the open `an-alle`; exit 3 on #push-sperre,
#                                          4 on #release-sperre with --release; 0 otherwise (also when gh is missing)
# Needs `gh` with access to happychriss/onpath.private. Cloud sessions without `gh` use their GitHub tool with the same
# repo, labels and shape.
set -uo pipefail
REPO=${ONPATH_ASK_REPO:-happychriss/onpath.private}
FOOTER=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

die() { echo "ask: $*" >&2; exit 2; }
have_gh() { command -v gh >/dev/null && gh api "repos/$REPO" --silent >/dev/null 2>&1; }

cmd=${1:-}; shift || true
ARGS=()
VON="" TITEL="" WORUM="" FRAGE="" A="" B="" C="" DETAILS="" TEXT="" RELEASE=0
while [ $# -gt 0 ]; do
  case "$1" in
    --von) VON=$2; shift ;;
    --titel) TITEL=$2; shift ;;
    --worum) WORUM=$2; shift ;;
    --frage) FRAGE=$2; shift ;;
    --a) A=$2; shift ;;
    --b) B=$2; shift ;;
    --c) C=$2; shift ;;
    --details) DETAILS=$2; shift ;;
    --text) TEXT=$2; shift ;;
    --release) RELEASE=1 ;;
    -h|--help) sed -n '2,/^set -uo/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
    *) ARGS+=("$1") ;;
  esac
  shift
done

ensure_labels() {
  gh api "repos/$REPO/labels" -f name=frage -f color=1d76db -f description="Frage an den Owner (tools/ask.sh)" --silent >/dev/null 2>&1 || true
  gh api "repos/$REPO/labels" -f name=an-alle -f color=d93f0b -f description="Wort des Owners an alle Sitzungen (tools/ask.sh)" --silent >/dev/null 2>&1 || true
}
# REST only (GraphQL – `gh issue …` – is blocked in cloud sessions)
new_issue() { # label title body → prints the URL
  gh api "repos/$REPO/issues" -f title="$2" -f body="$3" -f "labels[]=$1" --jq .html_url
}
open_issues() { # label → JSON array [{number,title,body,comments:[bodies]}]
  local list out='[]' nr c
  list=$(gh api "repos/$REPO/issues?labels=$1&state=open&per_page=100" \
    --jq '[.[] | select(.pull_request | not) | {number, title, body: (.body // ""), n: .comments}]') || return 1
  for nr in $(jq -r '.[].number' <<<"$list"); do
    if [ "$(jq -r --argjson n "$nr" '.[] | select(.number == $n) | .n' <<<"$list")" = 0 ]; then c='[]'
    else c=$(gh api "repos/$REPO/issues/$nr/comments?per_page=100" --jq '[.[].body]') || return 1; fi
    out=$(jq --argjson n "$nr" --argjson c "$c" '. + [{number: $n, comments: $c}]' <<<"$out")
  done
  jq -s '.[0] as $l | .[1] as $c | [$l[] | . as $i | $i + {comments: ([$c[] | select(.number == $i.number)][0].comments // [])}]' \
    <(echo "$list") <(echo "$out")
}
comment() { gh api "repos/$REPO/issues/$1/comments" -f body="$2" --silent; }

case "$cmd" in
  frage)
    [ -n "$VON" ] && [ -n "$TITEL" ] && [ -n "$FRAGE" ] && [ -n "$A" ] && [ -n "$B" ] || die "frage needs --von --titel --frage --a --b"
    have_gh || die "gh cannot reach $REPO"
    ensure_labels
    body="**Wer:** $VON"$'\n\n'"**Worum:** ${WORUM:-–}"$'\n\n'"**Frage:** $FRAGE"$'\n\n'"- **A)** $A"$'\n'"- **B)** $B"
    [ -n "$C" ] && body+=$'\n'"- **C)** $C"
    [ -n "$DETAILS" ] && body+=$'\n\n'"**Details:** $DETAILS"
    body+=$'\n\n'"Antwort: einen Kommentar mit dem Buchstaben (oder eigenem Text)."
    new_issue frage "[$VON] $TITEL" "$body$FOOTER"
    ;;
  offen)
    have_gh || die "gh cannot reach $REPO"
    json=$(open_issues frage) || die "could not list questions"
    jq -r '.[] | "#\(.number) \(.title)\n   Antwort: \(if (.comments|length) > 0 then (.comments[-1]|split("\n")[0]) else "– noch keine –" end)"' <<<"$json" |
      { if [ -n "$VON" ]; then grep -A1 -F "[$VON]" | grep -v '^--$'; else cat; fi; }
    ;;
  erledigt)
    nr=${ARGS[0]:-}; what=${ARGS[1]:-}
    [ -n "$nr" ] && [ -n "$what" ] || die "erledigt needs <nr> \"was gemacht wurde\""
    have_gh || die "gh cannot reach $REPO"
    comment "$nr" "Erledigt: $what$FOOTER" &&
      gh api -X PATCH "repos/$REPO/issues/$nr" -f state=closed -f state_reason=completed --silent && echo "#$nr geschlossen"
    ;;
  sag)
    [ -n "$TITEL" ] && [ -n "$TEXT" ] || die "sag needs --titel --text"
    have_gh || die "gh cannot reach $REPO"
    ensure_labels
    new_issue an-alle "$TITEL" "$TEXT$FOOTER"
    ;;
  an-alle|check)
    if ! have_gh; then
      echo "ask: ⚠ gh cannot reach $REPO – open 'an-alle' issues NOT checked (read them on GitHub)" >&2
      exit 0
    fi
    json=$(open_issues an-alle) ||
      { echo "ask: ⚠ could not list 'an-alle' issues – NOT checked" >&2; exit 0; }
    n=$(jq length <<<"$json")
    [ "$n" = 0 ] && { [ "$cmd" = an-alle ] && echo "an-alle: nichts offen"; exit 0; }
    jq -r '.[] | "an-alle #\(.number): \(.title)\n\(.body | split("\n---\n")[0] | split("\n") | map("   " + .) | join("\n"))"' <<<"$json"
    if [ "$cmd" = an-alle ] && [ -n "$VON" ]; then
      for nr in $(jq -r --arg v "gelesen – $VON" '.[] | select([.comments[] | startswith($v)] | any | not) | .number' <<<"$json"); do
        comment "$nr" "gelesen – $VON$FOOTER" && echo "   → #$nr als gelesen bestätigt ($VON)"
      done
    fi
    if [ "$cmd" = check ]; then
      if jq -e '[.[] | (.title + " " + .body) | test("#push-sperre")] | any' <<<"$json" >/dev/null; then
        echo "ask: ⛔ #push-sperre in an open 'an-alle' issue – no push until the owner closes it"; exit 3
      fi
      if [ "$RELEASE" = 1 ] && jq -e '[.[] | (.title + " " + .body) | test("#release-sperre")] | any' <<<"$json" >/dev/null; then
        echo "ask: ⛔ #release-sperre in an open 'an-alle' issue – no release commit until the owner closes it"; exit 4
      fi
    fi
    ;;
  *) die "unknown command '${cmd}' (frage | offen | erledigt | an-alle | sag | check; --help)" ;;
esac
