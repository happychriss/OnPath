#!/usr/bin/env python3
"""Writes a JVM stand-in for the :strings module (com.onpath.strings.Res / Txt + Compose's StringResource) from the
English strings_*.xml, so the routing harness compiles the app's Kotlin without Android or Compose resources.
Usage: strings_stub.py <repoRoot> <out.kt>"""
import re, sys, glob, html
root, out = sys.argv[1], sys.argv[2]
names, texts, plurals = [], {}, {}
def clean(t): return html.unescape(t).replace("\\'", "'").replace('\\"', '"')
for f in sorted(glob.glob(f"{root}/strings/src/commonMain/composeResources/values/strings_*.xml")):
    x = open(f, encoding="utf-8").read()
    for m in re.finditer(r'<string name="([A-Za-z0-9_]+)"[^>]*>(.*?)</string>', x, re.S):
        names.append(m.group(1)); texts[m.group(1)] = clean(m.group(2))
    for m in re.finditer(r'<plurals name="([A-Za-z0-9_]+)"[^>]*>(.*?)</plurals>', x, re.S):
        items = dict(re.findall(r'<item quantity="(\w+)">(.*?)</item>', m.group(2), re.S))
        plurals[m.group(1)] = (clean(items.get("one", items.get("other", ""))), clean(items.get("other", "")))
def kt(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n")
with open(out, "w", encoding="utf-8") as o:
    o.write("// generated by strings_stub.py – do not edit\n")
    o.write("package org.jetbrains.compose.resources\nclass StringResource(val key: String, val text: String)\n")
    o.write("class PluralStringResource(val key: String, val one: String, val other: String)\n")
    o.write("\n@file:Suppress(\"unused\")\n" if False else "")
with open(out.replace(".kt", "Res.kt"), "w", encoding="utf-8") as o:
    o.write("// generated by strings_stub.py – do not edit\npackage com.onpath.strings\n")
    o.write("import org.jetbrains.compose.resources.StringResource\n")
    # like Compose's generated accessors: top-level extension properties (imported as com.onpath.strings.<key>)
    o.write("object Res { object string; object plurals }\n")
    for n in names: o.write(f'val Res.string.{n}: StringResource get() = StringResource("{n}", "{kt(texts[n])}")\n')
    for n, (one, other) in plurals.items():
        o.write(f'val Res.plurals.{n}: org.jetbrains.compose.resources.PluralStringResource get() = '
                f'org.jetbrains.compose.resources.PluralStringResource("{n}", "{kt(one)}", "{kt(other)}")\n')
    o.write("object Txt {\n    fun language(): String = \"en\"\n")
    o.write("    fun s(res: StringResource, vararg args: Any): String = if (args.isEmpty()) res.text else String.format(java.util.Locale.US, res.text, *args)\n")
    o.write("    fun p(res: org.jetbrains.compose.resources.PluralStringResource, count: Int, vararg args: Any): String =\n")
    o.write("        String.format(java.util.Locale.US, if (count == 1) res.one else res.other, *args)\n}\n")
print(len(names), "strings")
